import {
    Router
} from "express";


import {
    neo4jHealth,
    syncKnowledgeGraph,
    graphOverview,
    graphNodes,
    graphNeighbourhood,
    graphSearch,
    graphPath,
    graphStats
} from "../controllers/neo4j.controller";


import {
    authenticateToken
} from "../middleware/auth.middleware";


const router =
    Router();


/*
|--------------------------------------------------------------------------
| Health
|--------------------------------------------------------------------------
*/

router.get(
    "/health",
    neo4jHealth
);


/*
|--------------------------------------------------------------------------
| Synchronisation
|--------------------------------------------------------------------------
*/

router.post(
    "/sync",
    authenticateToken,
    syncKnowledgeGraph
);


/*
|--------------------------------------------------------------------------
| Overview
|--------------------------------------------------------------------------
*/

router.get(
    "/overview",
    graphOverview
);


/*
|--------------------------------------------------------------------------
| Nodes
|--------------------------------------------------------------------------
*/

router.get(
    "/nodes",
    graphNodes
);


/*
|--------------------------------------------------------------------------
| Neighbourhood
|--------------------------------------------------------------------------
*/

router.get(
    "/nodes/:id/neighbourhood",
    graphNeighbourhood
);


/*
|--------------------------------------------------------------------------
| Search
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    graphSearch
);


/*
|--------------------------------------------------------------------------
| Shortest path
|--------------------------------------------------------------------------
*/

router.get(
    "/path",
    graphPath
);


/*
|--------------------------------------------------------------------------
| Statistics
|--------------------------------------------------------------------------
*/

router.get(
    "/stats",
    graphStats
);


export default router;